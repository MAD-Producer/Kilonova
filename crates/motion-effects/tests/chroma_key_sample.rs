//! Validate the distributed SDK sample with the real loader, not hand-made metadata.
use motion_effects::{package_directory, AlphaMode, EffectPackage, WorkingSpace};
use std::path::Path;

#[test]
fn chroma_key_sdk_sample_passes_actual_package_and_shader_validation() {
    let source = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../sdk/examples/chroma-key");
    let package = EffectPackage::from_bytes(package_directory(&source).unwrap()).unwrap();
    assert_eq!(package.manifest.id, "example.motionstudio.chroma-key");
    let effect = &package.manifest.effects[0];
    assert_eq!(package.manifest.effects.len(), 1);
    assert_eq!(effect.id, "chroma_key");
    assert_eq!(effect.working_space, WorkingSpace::Linear);
    assert_eq!(effect.alpha_mode, AlphaMode::Straight);
    assert_eq!(effect.passes.len(), 1);
    assert_eq!(
        effect
            .params
            .iter()
            .map(|p| p.id.as_str())
            .collect::<Vec<_>>(),
        ["key_color", "tolerance", "softness", "spill"]
    );
    assert!(effect.params.iter().all(|p| p.animatable));
    assert_eq!(effect.params[0].default, [0., 1., 0., 1.]);
    assert_eq!(effect.params[1].min, 0.);
    assert_eq!(effect.params[2].min, 0.);
    assert_eq!(effect.params[3].max, 1.);
    // Package generation goes through the real declared-file plan. Read back
    // the generated bytes rather than accepting successful source parsing only.
    let again = EffectPackage::from_bytes(package.bytes.clone()).unwrap();
    assert_eq!(package.hash, again.hash);
    assert_eq!(package.manifest, again.manifest);
}
